/// Render the report.
pub(crate) fn render(
    problem: &Problem,
    solution: &Solution,
    observed_at: &str,
    result_content_hash: &str,
    validation: &Value,
) -> String {
    let mut html = String::with_capacity(16 * 1024);

    html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
    html.push_str("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n");
    let _ = writeln!(
        html,
        "<title>Ordinata report: {}</title>",
        escape_html(&problem.title)
    );
    html.push_str("<style>\n");
    html.push_str(STYLE);
    html.push_str("</style>\n</head>\n<body>\n");

    let _ = writeln!(html, "<h1>{}</h1>", escape_html(&problem.title));
    if let Some(description) = &problem.description {
        let _ = writeln!(html, "<p>{}</p>", escape_html(description));
    }

    if problem.synthetic {
        html.push_str(
            "<div class=\"banner synthetic\"><strong>Synthetic demonstration data.</strong> \
             Every number below was generated by Ordinata to show what a bundle looks like. \
             None of it was measured. It describes nothing in the world.</div>\n",
        );
    }

    html.push_str(
        "<div class=\"banner refused\">This is a fitted result, not a measurement. The estimates, \
         predictions, and any bootstrap samples below are what a declared linear model produces \
         from the declared observations and their declared standard errors. They inherit every \
         assumption listed at the foot of this page.</div>\n",
    );

    render_warnings(&mut html, solution);
    render_provenance(
        &mut html,
        problem,
        solution,
        observed_at,
        result_content_hash,
    );
    render_diagnostics(&mut html, problem, solution);
    render_validation(&mut html, validation);
    render_parameters(&mut html, problem, solution);
    render_gcv(&mut html, problem, solution);
    render_fit(&mut html, problem, solution);
    render_declarations(&mut html, problem);

    let _ = writeln!(
        html,
        "<footer>{} {} &middot; {} &middot; {}</footer>",
        escape_html(spec::TOOL_NAME),
        escape_html(spec::TOOL_VERSION),
        escape_html(spec::PUBLISHER),
        escape_html(spec::SUPPORT_CONTACT),
    );
    html.push_str("</body>\n</html>\n");
    html
}

fn render_warnings(html: &mut String, solution: &Solution) {
    if solution.warnings.is_empty() {
        return;
    }
    html.push_str("<h2>Warnings</h2>\n");
    for warning in &solution.warnings {
        let _ = writeln!(
            html,
            "<div class=\"banner warn\"><strong>{}</strong><br>{}</div>",
            escape_html(warning.code),
            escape_html(&warning.message)
        );
    }
}

fn render_provenance(
    html: &mut String,
    problem: &Problem,
    solution: &Solution,
    observed_at: &str,
    result_content_hash: &str,
) {
    html.push_str("<h2>Provenance</h2>\n<dl>\n");
    let mut row = |key: &str, value: &str| {
        let _ = writeln!(
            html,
            "<dt>{}</dt><dd>{}</dd>",
            escape_html(key),
            escape_html(value)
        );
    };
    row(
        "Tool",
        &format!("{} {}", spec::TOOL_NAME, spec::TOOL_VERSION),
    );
    row("Model version", &spec::MODEL_VERSION.to_string());
    row("Build target", env!("ORDINATA_TARGET"));
    row("Observed at", observed_at);
    row("Result content hash", result_content_hash);
    row(
        "Data",
        if problem.synthetic {
            "synthetic, generated by Ordinata"
        } else {
            "supplied by the user"
        },
    );
    row(
        "Rank",
        &format!("{} of {}", solution.rank, problem.columns()),
    );
    html.push_str("</dl>\n");

    html.push_str("<h2>Input files</h2>\n<table>\n<tr><th>Role</th><th>Path as declared</th><th>SHA-256</th><th>Bytes</th></tr>\n");
    for input in &problem.source_inputs {
        let _ = writeln!(
            html,
            "<tr>{}{}{}<td class=\"n\">{}</td></tr>",
            cell(&input.role),
            cell(&input.path),
            cell(&input.sha256),
            input.bytes
        );
    }
    html.push_str("</table>\n");
    html.push_str("<p class=\"note\">These hashes are of the files exactly as they were supplied. The bundle also carries normalized copies under <code>inputs/</code>, which are the same data in canonical row and column order.</p>\n");
}

fn render_diagnostics(html: &mut String, problem: &Problem, solution: &Solution) {
    html.push_str("<h2>Diagnostics</h2>\n<dl>\n");
    let mut row = |key: &str, value: String| {
        let _ = writeln!(
            html,
            "<dt>{}</dt><dd>{}</dd>",
            escape_html(key),
            escape_html(&value)
        );
    };
    row(
        "Dimensions",
        format!(
            "{} observations, {} parameters",
            problem.rows(),
            problem.columns()
        ),
    );
    row(
        "Numerical rank",
        format!(
            "{} (tolerance {})",
            solution.rank,
            format_number(solution.rank_tolerance)
        ),
    );
    row(
        "Condition number",
        solution.condition_number.map_or_else(
            || "not finite: the design is rank deficient".to_string(),
            format_number,
        ),
    );
    row(
        "Lambda",
        format!(
            "{} ({})",
            format_number(solution.lambda),
            if solution.lambda_mode == "gcv" {
                "chosen by generalized cross-validation"
            } else {
                "declared in the project"
            }
        ),
    );
    row(
        "Effective degrees of freedom",
        format_number(solution.effective_dof),
    );
    row(
        "Residual degrees of freedom",
        format_number(solution.residual_dof),
    );
    row("Weighted RMSE", format_number(solution.weighted_rmse));
    row(
        "Reduced chi-square",
        solution.reduced_chi_square.map_or_else(
            || "not defined: no residual degrees of freedom".to_string(),
            |v| {
                format!(
                    "{} (near 1 means the declared standard errors match the residuals)",
                    format_number(v)
                )
            },
        ),
    );
    row(
        "Uncertainty requested",
        problem.uncertainty.method.as_str().to_string(),
    );
    html.push_str("</dl>\n");

    if solution.analytic.status == UncertaintyStatus::Refused
        || solution.bootstrap.status == UncertaintyStatus::Refused
    {
        html.push_str("<h2>Uncertainty was refused</h2>\n");
        for (label, status, reason) in [
            (
                "Analytic covariance",
                solution.analytic.status,
                solution.analytic.reason.as_ref(),
            ),
            (
                "Bootstrap",
                solution.bootstrap.status,
                solution.bootstrap.reason.as_ref(),
            ),
        ] {
            if status == UncertaintyStatus::Refused {
                let text = reason.map_or("", String::as_str);
                let _ = writeln!(
                    html,
                    "<div class=\"banner refused\"><strong>{}</strong><br>{}</div>",
                    escape_html(label),
                    escape_html(text)
                );
            }
        }
    }
}

fn render_validation(html: &mut String, validation: &Value) {
    html.push_str("<h2>Declared checks</h2>\n");
    let overall = validation
        .get("status")
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    let class = match overall {
        "pass" => "pass",
        "fail" => "fail",
        _ => "na",
    };
    let _ = writeln!(
        html,
        "<p>Overall: <span class=\"{}\">{}</span></p>",
        class,
        escape_html(overall)
    );
    html.push_str("<table>\n<tr><th>Check</th><th>Declared limit</th><th>Source</th><th>Observed</th><th>Result</th></tr>\n");
    if let Some(checks) = validation.get("checks").and_then(Value::as_array) {
        for check in checks {
            let get = |key: &str| check.get(key).and_then(Value::as_str).unwrap_or("");
            let number = |key: &str| {
                check
                    .get(key)
                    .and_then(Value::as_f64)
                    .map_or_else(|| "-".to_string(), format_number)
            };
            let status = get("status");
            let status_class = match status {
                "pass" => "pass",
                "fail" => "fail",
                _ => "na",
            };
            let _ = writeln!(html,
                "<tr>{}<td class=\"n\">{}</td>{}<td class=\"n\">{}</td><td><span class=\"{}\">{}</span></td></tr>",
                cell(get("name")),
                escape_html(&number("declaredThreshold")),
                cell(get("thresholdSource")),
                escape_html(&number("observed")),
                status_class,
                escape_html(status),
            );
        }
    }
    html.push_str("</table>\n");
    html.push_str("<p class=\"note\">These are the checks the project declared. Passing them is a statement about the user's own criteria, not a statement by Ordinata that the result is fit for any purpose.</p>\n");
}

/// The parameter table.
///
/// Every interval that was computed gets a column. A method that was asked for and
/// emitted is shown; a method that was asked for and refused is *said* to have been
/// refused, in the section above this one, rather than left as an empty column a
/// reader might take for a narrow one.
///
/// The two intervals are shown side by side rather than reconciled, because they are
/// not the same claim. The analytic interval believes the standard errors the project
/// declared. The bootstrap interval believes the residuals the fit actually left. When
/// those two beliefs disagree, the widths disagree, and that disagreement is
/// information -- it is the reduced chi-square, made visible. Averaging them, or
/// quietly showing whichever is wider, would destroy exactly the signal a reviewer
/// opens this file to find.
fn render_parameters(html: &mut String, problem: &Problem, solution: &Solution) {
    let analytic = solution.analytic.status == UncertaintyStatus::Emitted;
    let bootstrap = solution.bootstrap.status == UncertaintyStatus::Emitted;
    let percent = problem.uncertainty.confidence_level * 100.0;

    html.push_str("<h2>Parameters</h2>\n");
    let _ = writeln!(html,
        "<p class=\"note\">Interval shown in <code>parameters.csv</code> as <code>interval_lower</code>/<code>interval_upper</code>: {}. Every interval that was computed is also carried in a column of its own, here and in the bundle; none is dropped.</p>",
        escape_html(&crate::bundle::interval_description(
            solution,
            problem.uncertainty.confidence_level
        ))
    );
    if analytic && bootstrap {
        let _ = writeln!(html,
            "<p class=\"note\">Both intervals were requested and both were produced. They will not agree in general, and they are not meant to: the {percent:.1}% analytic interval trusts the standard errors the project declared, and the {percent:.1}% bootstrap interval trusts the residuals this fit actually left. A wide gap between them is a statement about the declared errors, not a defect in either.</p>"
        );
    }

    html.push_str(
        "<table>\n<tr><th>Parameter</th><th>Estimate</th><th>Standard error</th><th>Lower</th><th>Upper</th><th>Source</th>",
    );
    if analytic {
        html.push_str("<th>Analytic lower</th><th>Analytic upper</th>");
    }
    if bootstrap {
        html.push_str("<th>Bootstrap lower</th><th>Bootstrap upper</th>");
    }
    html.push_str("<th>Prior</th><th>Penalty</th></tr>\n");

    for (j, name) in problem.parameters.iter().enumerate() {
        let reported = solution.reported_interval(j);
        html.push_str("<tr>");
        html.push_str(&cell(name));
        html.push_str(&number_cell(solution.estimates[j]));
        html.push_str(&optional_number_cell(
            solution.analytic.standard_errors.get(j).copied(),
        ));
        html.push_str(&optional_number_cell(reported.map(|(low, _)| low)));
        html.push_str(&optional_number_cell(reported.map(|(_, high)| high)));
        html.push_str(&cell(solution.interval_source.as_str()));
        if analytic {
            let bounds = solution.analytic_bounds(j);
            html.push_str(&optional_number_cell(bounds.map(|(low, _)| low)));
            html.push_str(&optional_number_cell(bounds.map(|(_, high)| high)));
        }
        if bootstrap {
            let bounds = solution.bootstrap_bounds(j);
            html.push_str(&optional_number_cell(bounds.map(|(low, _)| low)));
            html.push_str(&optional_number_cell(bounds.map(|(_, high)| high)));
        }
        html.push_str(&number_cell(problem.prior[j]));
        html.push_str(&number_cell(problem.penalty[j]));
        html.push_str("</tr>\n");
    }
    html.push_str("</table>\n");
}

fn render_gcv(html: &mut String, problem: &Problem, solution: &Solution) {
    if solution.gcv_candidates.is_empty() {
        return;
    }
    let LambdaPlan::Gcv { min, max, steps } = problem.lambda_plan else {
        return;
    };
    html.push_str("<h2>Generalized cross-validation</h2>\n");
    let _ = writeln!(html,
        "<p class=\"note\">{} candidates, log-spaced from {} to {} inclusive. Every candidate is listed, scored or not. An exact tie resolves toward the larger lambda.</p>",
        steps,
        escape_html(&format_number(min)),
        escape_html(&format_number(max)),
    );
    html.push_str("<table>\n<tr><th>Lambda</th><th>Score</th><th>Effective d.o.f.</th><th>Weighted RSS</th><th></th></tr>\n");
    for candidate in &solution.gcv_candidates {
        // Bit equality, not an epsilon. The selected lambda is *one of these
        // candidates* -- the same `f64`, copied, not a value computed a second time --
        // so there is nothing here for a tolerance to absorb, and a tolerance would
        // wrongly mark two neighbouring grid points as both selected on a fine grid.
        let selected = candidate.lambda.to_bits() == solution.lambda.to_bits();
        html.push_str("<tr>");
        html.push_str(&number_cell(candidate.lambda));
        html.push_str(&optional_number_cell(candidate.score));
        html.push_str(&number_cell(candidate.effective_dof));
        html.push_str(&number_cell(candidate.weighted_rss));
        html.push_str(if selected {
            "<td><strong>selected</strong></td>"
        } else {
            "<td></td>"
        });
        html.push_str("</tr>\n");
    }
    html.push_str("</table>\n");
}

fn render_fit(html: &mut String, problem: &Problem, solution: &Solution) {
    html.push_str("<h2>Fit</h2>\n");
    let total = problem.rows();
    let shown = total.min(MAX_FIT_ROWS);
    if shown < total {
        let _ = writeln!(html,
            "<p class=\"note\">Showing the first {shown} of {total} observations, in canonical order. All {total} are in <code>fit.csv</code>; none are omitted from the bundle.</p>"
        );
    }
    html.push_str("<table>\n<tr><th>Observation</th><th>Observed</th><th>Prediction</th><th>Residual</th><th>Standardized</th><th>Standard error</th></tr>\n");
    for i in 0..shown {
        html.push_str("<tr>");
        html.push_str(&cell(&problem.observation_ids[i]));
        html.push_str(&number_cell(problem.values[i]));
        html.push_str(&number_cell(solution.predictions[i]));
        html.push_str(&number_cell(solution.residuals[i]));
        html.push_str(&optional_number_cell(solution.standardized_residuals[i]));
        html.push_str(&number_cell(problem.standard_errors[i]));
        html.push_str("</tr>\n");
    }
    html.push_str("</table>\n");
}

fn render_declarations(html: &mut String, problem: &Problem) {
    html.push_str("<h2>Assumptions</h2>\n");
    html.push_str(&list(&problem.assumptions));
    html.push_str("<h2>Limitations</h2>\n");
    html.push_str(&list(&problem.limitations));

    if !problem.sources.is_empty() {
        html.push_str("<h2>Sources</h2>\n");
        html.push_str("<table>\n<tr><th>Label</th><th>Reference</th><th>Date</th></tr>\n");
        for source in &problem.sources {
            let _ = writeln!(
                html,
                "<tr>{}{}{}</tr>",
                cell(&source.label),
                cell(source.uri.as_deref().unwrap_or("")),
                cell(source.date.as_deref().unwrap_or("")),
            );
        }
        html.push_str("</table>\n");
        html.push_str("<p class=\"note\">Sources are recorded exactly as the project supplied them. Ordinata does not fetch them, does not check them, and does not render them as links.</p>\n");
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::panic, clippy::expect_used)]
    use super::*;

    #[test]
    fn html_metacharacters_are_escaped() {
        let escaped = escape_html("<script>alert(\"x\" & 'y')</script>");
        assert_eq!(
            escaped,
            "&lt;script&gt;alert(&quot;x&quot; &amp; &#39;y&#39;)&lt;/script&gt;"
        );
        assert!(!escaped.contains('<'));
        assert!(!escaped.contains('>'));
        assert!(!escaped.contains('"'));
    }

    #[test]
    fn the_ampersand_is_escaped_first_so_escapes_are_not_double_escaped() {
        assert_eq!(escape_html("&lt;"), "&amp;lt;");
    }
}
