//! The static HTML report.
//!
//! The report is a single self-contained file. It has no script, no stylesheet link,
//! no image, no font, and no anchor. Everything it needs is inside it, which means it
//! renders identically on a machine with no network and reveals nothing to anyone if
//! it is opened on one that has.
//!
//! A citation URI the user supplied is printed as *text*, never as a link. A project
//! is a document someone else may have written, and turning a string from it into a
//! clickable target is how a `javascript:` URI or a tracking pixel would get a foot
//! in the door. Ordinata never fetches a citation and never invites the reader's
//! browser to either.
//!
//! Free text is escaped on the way in. Identifiers cannot contain a character that
//! needs escaping in the first place; see [`crate::text`].

use std::fmt::Write as _;

use serde_json::Value;

use crate::bundle::format_number;
use crate::ingest::{LambdaPlan, Problem};
use crate::solve::{Solution, UncertaintyStatus};
use crate::spec;

/// How many rows of the fit table to show before saying so and stopping.
const MAX_FIT_ROWS: usize = 200;

/// Escape text for HTML. Quotes are escaped too, so a value is safe in an attribute
/// as well as in a body, and nobody has to remember which context they are in.
pub(crate) fn escape_html(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 16);
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
    out
}

fn cell(text: &str) -> String {
    format!("<td>{}</td>", escape_html(text))
}

fn number_cell(value: f64) -> String {
    format!(
        "<td class=\"n\">{}</td>",
        escape_html(&format_number(value))
    )
}

fn optional_number_cell(value: Option<f64>) -> String {
    match value {
        Some(v) => number_cell(v),
        None => "<td class=\"n none\">not defined</td>".to_string(),
    }
}

fn list(items: &[String]) -> String {
    let mut out = String::from("<ul>");
    for item in items {
        let _ = write!(out, "<li>{}</li>", escape_html(item));
    }
    out.push_str("</ul>");
    out
}

